SPACE = 3
NO_BOLD = set("·⚡♪♫▶📍🐱🌧▬●─")   # icons and bar pieces keep their exact shapes


def _glyph(ch):
    rows = _G.get(ch)
    if rows is None:
        raise ValueError(f"pixelfont has no glyph for {ch!r}")
    rows = rows.split()
    w = len(rows[0])
    assert all(len(r) == w for r in rows) and len(rows) <= ROWS, f"bad glyph {ch!r}"
    g = np.zeros((ROWS, w), bool)
    for y, r in enumerate(rows):
        g[y] = [c == "#" for c in r]
    return g


GLYPHS = {c: _glyph(c) for c in _G}


def _bold(g):
    """Double-strike (OR with itself shifted 1 px right), first widening every 1-px gap to 2 px so it stays
    open: otherwise m, w, k, v, x, M, N, W, & fill in and read as blobs."""
    h, w = g.shape
    dup = {c for c in range(1, w - 1) if np.any(g[:, c - 1] & ~g[:, c] & g[:, c + 1])}
    if dup:
        g = np.stack([g[:, c] for c in range(w) for _ in range(2 if c in dup else 1)], 1)
    out = np.zeros((h, g.shape[1] + 1), bool)
    out[:, :-1] |= g
    out[:, 1:] |= g
    return out


def render(text, tracking=1, bold=False, italic=False, space=SPACE):
    """Bool mask (ROWS, width) of one line of text; 1 px = one font pixel."""
    cols = []
    for i, ch in enumerate(text):
        if ch == " ":
            cols.append(np.zeros((ROWS, space), bool))
        else:
            g = GLYPHS[ch]
            if bold and ch not in NO_BOLD:
                g = _bold(g)
            cols.append(g)
        if i < len(text) - 1:
            cols.append(np.zeros((ROWS, tracking), bool))
    m = np.concatenate(cols, 1) if cols else np.zeros((ROWS, 0), bool)
    if italic:
        # shear: rows above the baseline move right, 1 px per 3 rows (descenders move left)
        shift = [(BASE - 1 - y) // 3 for y in range(ROWS)]
        lo, hi = min(shift), max(shift)
        out = np.zeros((ROWS, m.shape[1] + hi - lo), bool)
        for y in range(ROWS):
            out[y, shift[y] - lo: shift[y] - lo + m.shape[1]] = m[y]
        m = out
    return m
