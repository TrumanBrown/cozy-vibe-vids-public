// buildTimeline: every generator together, and the seamless loop (loopTimeline).

import { r3 } from './random.js';
import { lightningStrikes } from './lightning.js';
import { rareEvents } from './spotlight.js';
import { ambientEvents } from './ambient.js';
import { weatherTrack } from './weather.js';
import { leafSchedule, petalSchedule } from './leaves.js';
import { lightSchedule, windowSchedule } from './lights.js';
import { petSchedule } from './pet.js';

// spec: { lightning: { perHour, cluster: [min, max], withinCluster: [s, s], minGap, maxGap, startAfter, endBefore, delay: [s, s], brightness },
//         lights: { offFrom, offTo, stayOn, revisit, fade }, windows: { pass, dim, away (per hour), minGap },
//         lantern / boat / heron: { perHour, dur, cooldown, startAfter, ... } (spotlight events, one at a time;
//         boat.ambient: true makes boats everyday traffic instead, see ambientEvents),
//         fish / flurry / farflash: { perHour, minGap, ... } (ambient events), weather, leaves, pet, strikeBusy: [s before, s after thunder],
//         loop: { period: s } (a seamless loop: see loopTimeline) }
// plate: the plate's plate.json (light_groups) when the scene is plate-based (switchable lights).
export function buildTimeline(spec, opts = {}) {
  const P = spec?.loop?.period ?? 0;
  if (P > 0 && !opts._period) return loopTimeline(spec, opts, P);
  const { seed = 1, duration = 36000, fps = 30, plate = null } = opts;
  const events = lightningStrikes(spec?.lightning, seed, duration);
  const strikes = events.slice();
  const groups = plate?.light_groups ?? [];
  // Spotlight events (boat, heron, lantern gutter) keep clear of each strike, from just before the flash
  // until its thunder has rolled; they can still happen between the strikes of a passing storm.
  const [sb0, sb1] = spec?.strikeBusy ?? [45, 45];
  const busy = strikes.map((e) => [e.t - sb0, e.thunder.t + sb1]);
  events.push(...rareEvents(spec, seed, duration, busy, groups));
  events.push(...ambientEvents(spec, seed, duration, events, plate?.regions ?? []));
  events.sort((a, b) => a.t - b.t || (a.type < b.type ? -1 : 1));
  events.forEach((e, i) => { e.id = i; e.frame = Math.round(e.t * fps); });
  const track = weatherTrack(spec?.weather, seed, duration, strikes, opts._period ?? 0);
  const flurries = events.filter((e) => e.type === 'flurry');
  const leaves = spec?.leaves ? leafSchedule(spec.leaves, seed, duration, track, flurries) : [];
  const petals = spec?.petals ? petalSchedule(spec.petals, seed, duration, track, flurries) : [];
  const winIds = groups.filter((g) => g.kind === 'window' && !g.reflective).map((g) => g.id);
  const lights = spec?.lights ? lightSchedule(spec.lights, seed, duration, winIds) : [];
  // Presence events only on windows big enough to see a change (>= minSize px across at 4K).
  const presIds = groups.filter((g) => g.kind === 'window' && !g.reflective && g.size_px >= (spec?.windows?.minSize ?? 10)).map((g) => g.id);
  const windows = spec?.windows ? windowSchedule(spec.windows, seed, duration, presIds, lights) : [];
  const pet = spec?.pet ? petSchedule(spec.pet, seed, duration, events) : [];
  return { version: 4, seed, duration, fps, events, track, leaves, lights, windows, pet, ...(petals.length ? { petals } : {}) };
}

// A seamless loop (user 2026-10-19: a looped 10 to 20 minute render is enough, since no event is rarer than 3 to 6 times
// an hour, as long as nothing jumps on screen where it loops). The
// video is one period of P seconds (a whole number of the scene's base loop, loopSeconds) repeated; for the picture
// to run on across a join, the timeline itself repeats with period P: frame t and frame t + P are identical.
//   1. One period is generated by the usual generators (rates calibrated to P, so every event type with a rate of 3
//      an hour or more appears in it; the opening bursts, `first` and `intro`, open every period), with a weather
//      track that repeats with period P (weatherTrack `period`). Night lights (lights) can't repeat and are off;
//      `atStart` is unused (what spills over from the period before is already in progress at the start).
//   2. What runs past the end of the period comes back at its start (the period before spills over), so early events
//      that would clash with it are dropped: one-at-a-time things (an ant, a boat, a snail on its path, a moth, a
//      spotlight event, a perched bird's slot, a window) and minimum spacings (lightning, distant flashes, gusts and
//      every stream's minGap).
//   3. The period is repeated over [-P, duration + P) (event fields that hold absolute times move along: thunder.t).
// Copies keep their period's id, so everything keyed by id (audio waves) is the same in every copy.
function loopTimeline(spec, opts, P) {
  const { seed = 1, duration = 36000, fps = 30 } = opts;
  const lp = opts.loopSeconds;
  if (lp && Math.abs(P / lp - Math.round(P / lp)) > 1e-9) throw new Error(`loop.period ${P} s must be a whole number of the base loop (${lp} s)`);
  const base = { ...spec };
  delete base.loop;
  if (base.lights) { console.warn('timeline: night lights (lights) cannot loop; off in a looped video'); delete base.lights; }
  if (base.perch) base.perch = { ...base.perch, atStart: 0 };
  if (base.boat) base.boat = { ...base.boat, atStart: false };
  const B = buildTimeline(base, { ...opts, duration: P, _period: P });
  const keep = wrapRepair(B, P, spec);
  const K = Math.ceil(duration / P);
  const shift = (e, d) => {
    const c = { ...e, t: r3(e.t + d) };
    if (e.thunder) c.thunder = { ...e.thunder, t: r3(e.thunder.t + d) };
    return c;
  };
  const span = (e) => (e.dur ?? 0) + (e.thunder ? e.thunder.t - e.t + 30 : 0) + 60;
  const unroll = (list) => {
    const out = [];
    for (let k = -1; k <= K; k++) for (const e of list) { const c = shift(e, k * P); if (c.t + span(c) > -P && c.t < duration + P) out.push(c); }
    return out.sort((a, b) => a.t - b.t || (a.type < b.type ? -1 : a.type > b.type ? 1 : 0));
  };
  const events = unroll(keep.events);
  events.forEach((e) => { e.frame = Math.round(e.t * fps); });
  const T = B.track, m = Math.round(P / T.dt), n = Math.ceil(duration / T.dt) + 1;
  const tile = (a) => Array.from({ length: n }, (_, i) => a[i % m]);
  const track = { dt: T.dt, rain: tile(T.rain), streams: tile(T.streams), wind: tile(T.wind), period: P };
  const out = { version: 4, seed, duration, fps, loop: { period: P, dropped: keep.dropped }, events, track, leaves: unroll(B.leaves),
                lights: [], windows: unroll(keep.windows), pet: unroll(keep.pet) };
  if (B.petals) out.petals = unroll(B.petals);
  return out;
}

// Step 2 of loopTimeline: the period's early events that clash with what spills over from the period before.
function wrapRepair(B, P, spec) {
  const dropped = {};
  const drop = (type) => { dropped[type] = (dropped[type] ?? 0) + 1; };
  const prev = B.events.map((e) => ({ ...e, t: e.t - P }));
  // how long a one-at-a-time event occupies its place, and the gap after it
  const busyEnd = (e) => e.t + (e.dur ?? 0) + (e.type === 'ant' && e.n > 1 ? 40 : 0);
  const excl = { ant: 20, boat: 10, critter: 120, moth: 10, lantern: 60, heron: 60, train: 60, petact: 30 };
  const key = (e) => (e.type === 'critter' ? `critter${e.track ?? 0}` : e.type);
  const minGap = (type) => {
    if (type === 'lightning') return (spec.lightning?.withinCluster ?? [80, 300])[0];
    return spec[type]?.minGap ?? 0;
  };
  const strikesPrev = prev.filter((e) => e.type === 'lightning');
  const farClear = spec.farflash?.clear ?? 0;
  const events = [];
  for (const e of B.events) {
    let clash = false;
    if (excl[e.type] != null) clash = prev.some((p) => key(p) === key(e) && busyEnd(p) + excl[e.type] > e.t);
    else if (e.type === 'perch') {
      // a perched bird holds its slot from landing until it has flown off
      const held = prev.filter((p) => p.type === 'perch' && p.perch === e.perch).flatMap((p) => p.members.map((m) => [m.slot, p.t + m.land, p.t + m.leave + m.outT + 1]));
      const ms = e.members.filter((m) => !held.some(([s, a, b]) => s === m.slot && e.t + m.land < b && e.t + m.leave + m.outT + 1 > a));
      if (ms.length < e.members.length) {
        if (!ms.length) clash = true;
        else { e.members = ms; e.dur = r3(Math.max(...ms.map((m) => m.leave + m.outT)) + 0.5); }
      }
    } else {
      const g = minGap(e.type);
      if (g > 0) clash = prev.some((p) => p.type === e.type && e.t - p.t < g);
      if (!clash && e.type === 'farflash' && farClear) clash = strikesPrev.some((s) => Math.abs(e.t - s.t) < farClear);
    }
    if (clash) drop(e.type); else events.push(e);
  }
  // windows (a pane is busy for its dip plus a minute) and the pet's motions (its own minimum gap)
  const winPrev = (B.windows ?? []).map((w) => ({ ...w, t: w.t - P }));
  const windows = (B.windows ?? []).filter((w) => {
    const c = winPrev.some((p) => p.id === w.id && p.t + p.dur + 60 > w.t) || winPrev.some((p) => w.t - p.t < (spec.windows?.minGap ?? 45));
    if (c) drop('window');
    return !c;
  });
  const petPrev = (B.pet ?? []).map((p) => ({ ...p, t: p.t - P }));
  const pet = (B.pet ?? []).filter((e) => {
    const c = petPrev.some((p) => e.t < p.t + p.dur + (spec.pet?.minGap ?? 25));
    if (c) drop('pet');
    return !c;
  });
  return { events, windows, pet, dropped };
}
